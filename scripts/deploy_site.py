"""Deploy the static PWA to GitHub Pages (gh-pages orphan branch).

Usage (from the project root, after building):

    python -I scripts/build_site.py data/processed/network.json data/raw site
    python -I scripts/deploy_site.py site

Steps: temp-clone this repo, replace everything with the fresh build on
an orphan ``gh-pages`` branch, push it, then try to enable GitHub Pages
via the REST API using the stored git credential.  If the API call is
not permitted (token scope), the script prints the one-time manual step
(Settings -> Pages -> Source: gh-pages) instead.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import urllib.error
import urllib.request

REPO_URL = "https://github.com/Li-Baixi/MATH7005-Project2.git"
API_PAGES = "https://api.github.com/repos/Li-Baixi/MATH7005-Project2/pages"
SITE_URL = "https://li-baixi.github.io/MATH7005-Project2/"


def run(cmd, **kw):
    subprocess.run(cmd, check=True, **kw)


def deploy(site_dir: str) -> None:
    site_dir = os.path.abspath(site_dir)
    if not os.path.exists(os.path.join(site_dir, "index.html")):
        sys.exit(f"{site_dir} has no index.html — run build_site.py first")

    # keep the temp clone off the (often tiny) system drive if possible
    tmp_parent = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    tmp = tempfile.mkdtemp(prefix="accesshk-deploy-", dir=tmp_parent)
    repo = os.path.join(tmp, "repo")
    try:
        run(["git", "clone", "-q", "--no-hardlinks", ".", repo])
        run(["git", "-C", repo, "checkout", "-q", "--orphan", "gh-pages"])
        run(["git", "-C", repo, "rm", "-rqf", "."])
        for name in os.listdir(repo):
            if name != ".git":
                path = os.path.join(repo, name)
                shutil.rmtree(path) if os.path.isdir(path) else os.remove(path)
        for name in os.listdir(site_dir):
            src = os.path.join(site_dir, name)
            (shutil.copytree if os.path.isdir(src) else shutil.copy)(
                src, os.path.join(repo, name))
        run(["git", "-C", repo, "add", "-A"])
        run(["git", "-C", repo, "commit", "-q", "-m",
             "Deploy static PWA (generated by scripts/build_site.py)\n\n"
             "Co-Authored-By: Claude Code <noreply@anthropic.com>"])
        # gh-pages is a generated artefact: each deploy is a fresh orphan
        # commit, so the push must overwrite the previous one
        run(["git", "-C", repo, "push", "-q", "--force", REPO_URL,
             "HEAD:gh-pages"])
        print("pushed gh-pages branch")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def enable_pages() -> None:
    """Best effort: enable Pages from gh-pages via the stored git token."""
    try:
        cred = subprocess.run(
            ["git", "credential", "fill"],
            input=b"protocol=https\nhost=github.com\n\n",
            capture_output=True, check=True).stdout.decode()
        token = next(line.split("=", 1)[1].strip()
                     for line in cred.splitlines()
                     if line.startswith("password="))
    except Exception:
        token = None
    if not token:
        print("no stored GitHub token — enable Pages manually (see below)")
        return

    body = json.dumps({"source": {"branch": "gh-pages", "path": "/"}}).encode()
    req = urllib.request.Request(
        API_PAGES, data=body, method="POST",
        headers={"Authorization": f"Bearer {token}",
                 "Accept": "application/vnd.github+json",
                 "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req) as resp:
            print(f"Pages enabled ({resp.status})")
    except urllib.error.HTTPError as e:
        if e.code in (409, 422):            # already configured
            print("Pages already enabled")
        else:
            print(f"Pages API returned {e.code} — enable manually (see below)")


def main() -> None:
    deploy(sys.argv[1] if len(sys.argv) > 1 else "site")
    enable_pages()
    print(f"site will be live at: {SITE_URL} (first build takes ~1 min)")


if __name__ == "__main__":
    main()
